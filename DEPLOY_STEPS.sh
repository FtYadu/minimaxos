    echo ""
    echo "2. Click: 'Add new site' → 'Import an existing project'"
    echo ""
    echo "3. Choose: 'GitHub'"
    echo "   (Authorize Netlify if first time)"
    echo ""
    echo "4. Select repository: 'minimax-studio'"
    echo ""
    echo "5. Build settings (should be auto-detected):"
    echo "   ✓ Build command: npm run build"
    echo "   ✓ Publish directory: .next"
    echo "   ✓ Already configured in netlify.toml!"
    echo ""
    echo "6. Click: 'Deploy site'"
    echo ""
    echo "⏱️  Wait 2-3 minutes for build to complete..."
    echo ""
    echo "════════════════════════════════════════════════════════════════"
    echo ""
    echo "🎉 YOUR SITE WILL BE LIVE!"
    echo ""
    echo "Default URL: https://random-name-123.netlify.app"
    echo ""
