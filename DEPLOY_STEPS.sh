    echo "   • Click: Generate new token (classic)"
    echo "   • Select: repo (full control)"
    echo "   • Copy the token"
    echo "   • Use as PASSWORD when git asks"
    echo ""
    echo "2️⃣  Repository doesn't exist?"
    echo "   • Make sure you created it on GitHub"
    echo "   • Check name: minimax-studio"
    echo "   • Verify URL: $REPO_URL"
