echo "╔════════════════════════════════════════════════════════════════╗"
echo "║                                                                ║"
echo "║           🚀 MiniMax Studio - Ready to Deploy! 🚀              ║"
echo "║                                                                ║"
echo "╔════════════════════════════════════════════════════════════════╗"
echo ""
echo "📍 Current location: $(pwd)"
echo "✅ Git status:"
git log --oneline -3
echo ""
echo "════════════════════════════════════════════════════════════════"
echo ""
echo "📝 STEP 1: Create GitHub Repository"
echo "════════════════════════════════════════════════════════════════"
echo ""
echo "Go to: https://github.com/new"
echo ""
echo "Fill in:"
echo "  • Repository name: minimax-studio"
echo "  • Description: AI Content Generation Platform with MiniMax API"
echo "  • Public or Private: Your choice"
echo "  • ❌ DON'T check 'Initialize with README'"
echo "  • Click 'Create repository'"
echo ""
echo "════════════════════════════════════════════════════════════════"
echo ""
read -p "✋ Press Enter after creating the repository on GitHub..."
echo ""
echo "════════════════════════════════════════════════════════════════"
echo ""
echo "📝 STEP 2: What's your GitHub username?"
echo "════════════════════════════════════════════════════════════════"
echo ""
read -p "GitHub username: " USERNAME
echo ""

if [ -z "$USERNAME" ]; then
    echo "❌ Username required! Run the script again."
    exit 1
fi

REPO_URL="https://github.com/$USERNAME/minimax-studio.git"

echo "Your repository URL: $REPO_URL"
echo ""
echo "════════════════════════════════════════════════════════════════"
echo ""
echo "📝 STEP 3: Connecting to GitHub..."
echo "════════════════════════════════════════════════════════════════"
echo ""

# Check if remote exists
if git remote get-url origin &> /dev/null; then
    echo "🔄 Updating existing remote..."
    git remote set-url origin "$REPO_URL"
else
    echo "➕ Adding remote..."
    git remote add origin "$REPO_URL"
fi

echo "✅ Remote configured!"
echo ""
git remote -v
echo ""

echo "════════════════════════════════════════════════════════════════"
echo ""
echo "📝 STEP 4: Pushing to GitHub..."
echo "════════════════════════════════════════════════════════════════"
echo ""
echo "You may be asked for credentials..."
echo ""

git branch -M main
git push -u origin main

if [ $? -eq 0 ]; then
    echo ""
    echo "╔════════════════════════════════════════════════════════════════╗"
    echo "║                                                                ║"
    echo "║                   ✅ SUCCESS! CODE PUSHED! ✅                  ║"
    echo "║                                                                ║"
    echo "╚════════════════════════════════════════════════════════════════╝"
    echo ""
    echo "🔗 Your repo: https://github.com/$USERNAME/minimax-studio"
    echo ""
    echo "════════════════════════════════════════════════════════════════"
    echo ""
